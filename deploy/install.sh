#!/usr/bin/env bash
#
# REBLOS one-command installer.
#
#   curl -fsSL https://raw.githubusercontent.com/Freakoverse/REBLOS/main/deploy/install.sh | sudo bash
#
# Sets up a REBLOS node (NIP-CHAT relay + Blossom server) behind Caddy (automatic
# HTTPS) on a fresh Ubuntu/Debian server. Idempotent: re-running updates the node
# and never clobbers the identity key or data.
set -euo pipefail

REPO_URL="https://github.com/Freakoverse/REBLOS.git"
INSTALL_DIR="/opt/reblos"
BRANCH="main"

# Prompts must read from the terminal, not the piped script (curl | bash).
ask() { # ask <var> <prompt> [default]
	local __var="$1" __prompt="$2" __def="${3:-}" __ans=""
	if [ -n "$__def" ]; then __prompt="$__prompt [$__def]"; fi
	read -rp "$__prompt: " __ans </dev/tty || true
	printf -v "$__var" '%s' "${__ans:-$__def}"
}

err() { echo "error: $*" >&2; exit 1; }

[ "$(id -u)" = "0" ] || err "run as root (prefix with sudo)"

cat <<'EOF'

  REBLOS installer
  ================
  A NIP-CHAT relay + Blossom server for your hubs, behind automatic HTTPS.

  Before continuing, have ready:
    1. A domain or subdomain whose DNS A record ALREADY points at THIS server's
       public IP (if you use Cloudflare DNS, set it to "DNS only" / grey cloud).
    2. Your admin npub: the Nostr key that will manage this node's dashboard.
    3. If you'll use cloud storage: your Cloudflare R2 or S3 endpoint + keys.

EOF
read -rp "  Press Enter to continue (Ctrl-C to abort)... " _ </dev/tty || true
echo

# ── Questions ────────────────────────────────────────────────────────────────
ask DOMAIN "Domain for this node (e.g. relay.example.com)"
[ -n "$DOMAIN" ] || err "a domain is required"

ask ADMIN_NPUB "Admin npub (npub1…)"
case "$ADMIN_NPUB" in npub1*) ;; *) err "admin must be an npub1… key" ;; esac

ask GENKEY "Generate a relay Nostr keypair? (recommended: yes; say no to paste your own nsec, NOT your personal one)" "yes"
RELAY_NSEC=""
case "$GENKEY" in
	n | N | no | No | NO)
		ask RELAY_NSEC "Paste the relay nsec (nsec1…)"
		case "$RELAY_NSEC" in nsec1*) ;; *) err "that is not an nsec1… key" ;; esac
		;;
esac

echo
echo "  Storage backend:"
echo "    1) disk   : blobs on this server's disk (simplest)"
echo "    2) r2     : Cloudflare R2"
echo "    3) s3     : self-hosted S3 (MinIO / Garage / Ceph)"
ask STORAGE "  Choose" "1"

S3_ENDPOINT=""; S3_BUCKET=""; S3_ACCESS=""; S3_SECRET=""; BACKEND="disk"; PATH_STYLE="false"
case "$STORAGE" in
	2)
		BACKEND="r2"
		ask S3_ENDPOINT "R2 S3 endpoint (<accountid>.r2.cloudflarestorage.com)"
		ask S3_BUCKET "R2 bucket name"
		ask S3_ACCESS "R2 access key id"
		ask S3_SECRET "R2 secret access key"
		;;
	3)
		BACKEND="s3"; PATH_STYLE="true"
		ask S3_ENDPOINT "S3 endpoint host[:port] (no scheme)"
		ask S3_BUCKET "S3 bucket name"
		ask S3_ACCESS "S3 access key id"
		ask S3_SECRET "S3 secret access key"
		;;
	*) BACKEND="disk" ;;
esac

# ── DNS sanity check ─────────────────────────────────────────────────────────
echo
echo "  Checking DNS…"
SERVER_IP="$(curl -fsSL https://api.ipify.org 2>/dev/null || true)"
RESOLVED="$(getent hosts "$DOMAIN" 2>/dev/null | awk '{print $1}' | head -1 || true)"
if [ -n "$SERVER_IP" ] && [ -n "$RESOLVED" ] && [ "$RESOLVED" != "$SERVER_IP" ]; then
	echo "  WARNING: $DOMAIN resolves to '$RESOLVED', not this server's IP '$SERVER_IP'."
	echo "  Caddy's HTTPS certificate will fail until DNS points here."
	ask CO7 "  Continue anyway?" "no"
	case "$CO7" in y | Y | yes | Yes | YES) ;; *) err "aborted; point DNS at $SERVER_IP and re-run" ;; esac
elif [ -z "$RESOLVED" ]; then
	echo "  WARNING: could not resolve $DOMAIN yet (DNS may still be propagating)."
fi

# ── Docker ───────────────────────────────────────────────────────────────────
if ! command -v docker >/dev/null 2>&1; then
	echo "  Installing Docker…"
	curl -fsSL https://get.docker.com | sh
fi
docker compose version >/dev/null 2>&1 || err "the Docker Compose plugin is required (install Docker from get.docker.com)"

# ── Fetch / update the repo ──────────────────────────────────────────────────
if [ -d "$INSTALL_DIR/.git" ]; then
	echo "  Updating $INSTALL_DIR…"
	git -C "$INSTALL_DIR" fetch --depth 1 origin "$BRANCH"
	git -C "$INSTALL_DIR" reset --hard "origin/$BRANCH"
else
	command -v git >/dev/null 2>&1 || { apt-get update -y && apt-get install -y git; }
	echo "  Cloning REBLOS into $INSTALL_DIR…"
	git clone --depth 1 --branch "$BRANCH" "$REPO_URL" "$INSTALL_DIR"
fi

DEPLOY="$INSTALL_DIR/deploy"
mkdir -p "$DEPLOY/data"
chmod 700 "$DEPLOY/data"

# ── Config files (preserve an existing identity key) ─────────────────────────
PUBLIC_URL="https://$DOMAIN"

cat >"$DEPLOY/config.yml" <<EOF
# Generated by install.sh. Secrets live in .env, not here.
listen: ":3000"
public_url: "$PUBLIC_URL"
data_dir: "/app/data"
backend: "$BACKEND"

r2:
  endpoint: "$([ "$BACKEND" = r2 ] && echo "$S3_ENDPOINT")"
  region: "auto"
  bucket: "$([ "$BACKEND" = r2 ] && echo "$S3_BUCKET")"
  use_ssl: true

s3:
  endpoint: "$([ "$BACKEND" = s3 ] && echo "$S3_ENDPOINT")"
  region: "us-east-1"
  bucket: "$([ "$BACKEND" = s3 ] && echo "$S3_BUCKET")"
  use_ssl: true
  path_style: $PATH_STYLE

disk:
  path: "/app/data/blobs"

relay:
  admin_npub: "$ADMIN_NPUB"

download:
  trusted_ip_header: "X-Forwarded-For"

log:
  level: "info"
  format: "json"
EOF
# config.yml holds no secrets (those live in .env); it must be world-readable so the
# non-root container user (uid 10001) can read the read-only bind mount, or the node
# crash-loops on "config load failed: permission denied" and Caddy returns 502.
chmod 644 "$DEPLOY/config.yml"

: >"$DEPLOY/.env"
chmod 600 "$DEPLOY/.env"
if [ "$BACKEND" = "r2" ]; then
	printf 'R2_ACCESS_KEY=%s\nR2_SECRET_KEY=%s\n' "$S3_ACCESS" "$S3_SECRET" >"$DEPLOY/.env"
elif [ "$BACKEND" = "s3" ]; then
	printf 'S3_ACCESS_KEY=%s\nS3_SECRET_KEY=%s\n' "$S3_ACCESS" "$S3_SECRET" >"$DEPLOY/.env"
fi

cat >"$DEPLOY/Caddyfile" <<EOF
$DOMAIN {
	reverse_proxy node:3000
	request_body {
		max_size 550MB
	}
}
EOF

# Pre-seed a pasted relay key only when one isn't already present (never clobber).
if [ -n "$RELAY_NSEC" ] && [ ! -s "$DEPLOY/data/identity.key" ]; then
	printf '%s\n' "$RELAY_NSEC" >"$DEPLOY/data/identity.key"
	chmod 600 "$DEPLOY/data/identity.key"
fi

# ── Launch ───────────────────────────────────────────────────────────────────
echo
echo "  Building and starting (first run compiles the node; this can take a minute)…"
( cd "$DEPLOY" && docker compose up -d --build )

echo "  Waiting for the node to come up…"
RELAY_NPUB=""
for _ in $(seq 1 30); do
	RELAY_NPUB="$(cd "$DEPLOY" && docker compose logs node 2>/dev/null | grep -oE 'npub1[0-9a-z]+' | head -1 || true)"
	[ -n "$RELAY_NPUB" ] && break
	sleep 2
done

cat <<EOF

  ✔ REBLOS is up.

    Node URL:        $PUBLIC_URL
    Dashboard:       $PUBLIC_URL/dashboard
    Admin:           $ADMIN_NPUB
    Relay npub:      ${RELAY_NPUB:-"(see: cd $DEPLOY && docker compose logs node)"}

  Next:
    1. Open the dashboard and sign in with your admin Nostr extension.
    2. Add your hub by its naddr (Hubs tab).

  Manage:
    cd $DEPLOY
    docker compose logs -f node      # logs
    docker compose pull && docker compose up -d --build   # update
    docker compose down              # stop

  Back up $DEPLOY/data and $DEPLOY/.env: that is your whole node.

EOF
